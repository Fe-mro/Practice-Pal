// Practice Pal – Service Worker
// Zweck: App installierbar machen und die Oberfläche offline verfügbar halten.
// Keine Daten werden an Dritte gesendet; alles bleibt im Browser (localStorage).

const CACHE = 'practice-pal-v2';
const SHELL = ['/', '/index.html', '/manifest.webmanifest', '/icon-192.png', '/icon-512.png', '/apple-touch-icon.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;

  // Seiten: erst aus dem Netz (damit Updates ankommen), sonst aus dem Cache.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => { const copy = res.clone(); caches.open(CACHE).then((c) => c.put('/index.html', copy)); return res; })
        .catch(() => caches.match('/index.html'))
    );
    return;
  }

  // Übrige Dateien: Cache zuerst, sonst Netz.
  event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
